#include<stdio.h>
#include<stdlib.h>
#include<time.h>
#include<string.h>
#include<ctype.h>

int main()
{
	int a = 13;
	//或
	//13//00000000000000000000000000001101
	//29//00000000000000000000000000011101
	//  //11111111111111111111111111101111
	//11111111111111111111111111110010
	//11111111111111111111111111110001
	//10000000000000000000000000001110
	a |= (1 << 4);//转换为29
	printf("%d\n", a);
	a &= (~(1 << 4));//转换为13 /
	printf("%d\n", a);
	return 0;
}